-- Script DDL: creacion de las 12 tablas
-- Incluye metadatos JSONB en la tabla evento
-- No elimina ni modifica tablas existentes.
-- =========================================================

BEGIN;

-- 1. TABLA ESTUDIANTE
CREATE TABLE estudiante (
    id_estudiante INTEGER GENERATED ALWAYS AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    correo VARCHAR(150) NOT NULL,
    fecha_nacimiento DATE,
    CONSTRAINT pk_estudiante PRIMARY KEY (id_estudiante),
    CONSTRAINT uq_estudiante_correo UNIQUE (correo)
);

-- 2. TABLA INTERES
CREATE TABLE interes (
    id_interes INTEGER GENERATED ALWAYS AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT,
    CONSTRAINT pk_interes PRIMARY KEY (id_interes)
);

-- 3. TABLA HABILIDAD
CREATE TABLE habilidad (
    id_habilidad INTEGER GENERATED ALWAYS AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT,
    nivel VARCHAR(50),
    CONSTRAINT pk_habilidad PRIMARY KEY (id_habilidad)
);

-- 4. TABLA GRUPO
CREATE TABLE grupo (
    id_grupo INTEGER GENERATED ALWAYS AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT,
    tipo VARCHAR(50),
    fecha_creacion TIMESTAMP WITHOUT TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_grupo PRIMARY KEY (id_grupo)
);

-- 5. TABLA EVENTO
CREATE TABLE evento (
    id_evento INTEGER GENERATED ALWAYS AS IDENTITY,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    fecha DATE NOT NULL,
    hora TIME WITHOUT TIME ZONE NOT NULL,
    lugar VARCHAR(200),
    metadatos JSONB,
    CONSTRAINT pk_evento PRIMARY KEY (id_evento)
);

-- 6. TABLA PUBLICACION
CREATE TABLE publicacion (
    id_publicacion INTEGER GENERATED ALWAYS AS IDENTITY,
    id_estudiante INTEGER NOT NULL,
    contenido TEXT NOT NULL,
    fecha_publicacion TIMESTAMP WITHOUT TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo VARCHAR(50),
    CONSTRAINT pk_publicacion PRIMARY KEY (id_publicacion),
    CONSTRAINT fk_publicacion_id_estudiante
        FOREIGN KEY (id_estudiante)
        REFERENCES estudiante(id_estudiante)
);

-- 7. TABLA COMENTARIO
CREATE TABLE comentario (
    id_comentario INTEGER GENERATED ALWAYS AS IDENTITY,
    id_publicacion INTEGER NOT NULL,
    id_estudiante INTEGER NOT NULL,
    contenido TEXT NOT NULL,
    fecha_comentario TIMESTAMP WITHOUT TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_comentario PRIMARY KEY (id_comentario),
    CONSTRAINT fk_comentario_id_estudiante
        FOREIGN KEY (id_estudiante)
        REFERENCES estudiante(id_estudiante),
    CONSTRAINT fk_comentario_id_publicacion
        FOREIGN KEY (id_publicacion)
        REFERENCES publicacion(id_publicacion)
        ON DELETE CASCADE
);

-- 8. TABLA ESTUDIANTE_INTERES
CREATE TABLE estudiante_interes (
    id_estudiante INTEGER NOT NULL,
    id_interes INTEGER NOT NULL,
    CONSTRAINT pk_estudiante_interes
        PRIMARY KEY (id_estudiante, id_interes),
    CONSTRAINT fk_estudiante_interes_id_estudiante
        FOREIGN KEY (id_estudiante)
        REFERENCES estudiante(id_estudiante)
        ON DELETE CASCADE,
    CONSTRAINT fk_estudiante_interes_id_interes
        FOREIGN KEY (id_interes)
        REFERENCES interes(id_interes)
        ON DELETE CASCADE
);

-- 9. TABLA ESTUDIANTE_HABILIDAD
CREATE TABLE estudiante_habilidad (
    id_estudiante INTEGER NOT NULL,
    id_habilidad INTEGER NOT NULL,
    CONSTRAINT pk_estudiante_habilidad
        PRIMARY KEY (id_estudiante, id_habilidad),
    CONSTRAINT fk_estudiante_habilidad_id_estudiante
        FOREIGN KEY (id_estudiante)
        REFERENCES estudiante(id_estudiante)
        ON DELETE CASCADE,
    CONSTRAINT fk_estudiante_habilidad_id_habilidad
        FOREIGN KEY (id_habilidad)
        REFERENCES habilidad(id_habilidad)
        ON DELETE CASCADE
);

-- 10. TABLA SEGUIMIENTO
CREATE TABLE seguimiento (
    id_seguidor INTEGER NOT NULL,
    id_seguido INTEGER NOT NULL,
    id_seguimiento INTEGER GENERATED BY DEFAULT AS IDENTITY,
    fecha_seguimiento TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_seguimiento PRIMARY KEY (id_seguimiento),
    CONSTRAINT uq_seguimiento_pareja
        UNIQUE (id_seguidor, id_seguido),
    CONSTRAINT seguimiento_check
        CHECK (id_seguidor <> id_seguido),
    CONSTRAINT fk_seguimiento_id_seguido
        FOREIGN KEY (id_seguido)
        REFERENCES estudiante(id_estudiante)
        ON DELETE CASCADE,
    CONSTRAINT fk_seguimiento_id_seguidor
        FOREIGN KEY (id_seguidor)
        REFERENCES estudiante(id_estudiante)
        ON DELETE CASCADE
);

-- 11. TABLA MEMBRESIA
CREATE TABLE membresia (
    id_estudiante INTEGER NOT NULL,
    id_grupo INTEGER NOT NULL,
    fecha_ingreso TIMESTAMP WITHOUT TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_membresia INTEGER GENERATED BY DEFAULT AS IDENTITY,
    rol VARCHAR(50),
    CONSTRAINT pk_membresia PRIMARY KEY (id_membresia),
    CONSTRAINT uq_membresia_estudiante_grupo
        UNIQUE (id_estudiante, id_grupo),
    CONSTRAINT fk_membresia_id_estudiante
        FOREIGN KEY (id_estudiante)
        REFERENCES estudiante(id_estudiante)
        ON DELETE CASCADE,
    CONSTRAINT fk_membresia_id_grupo
        FOREIGN KEY (id_grupo)
        REFERENCES grupo(id_grupo)
        ON DELETE CASCADE
);

-- 12. TABLA PARTICIPACION_EVENTO
CREATE TABLE participacion_evento (
    id_estudiante INTEGER NOT NULL,
    id_evento INTEGER NOT NULL,
    fecha_inscripcion TIMESTAMP WITHOUT TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_participacion_evento
        PRIMARY KEY (id_estudiante, id_evento),
    CONSTRAINT fk_participacion_evento_id_estudiante
        FOREIGN KEY (id_estudiante)
        REFERENCES estudiante(id_estudiante)
        ON DELETE CASCADE,
    CONSTRAINT fk_participacion_evento_id_evento
        FOREIGN KEY (id_evento)
        REFERENCES evento(id_evento)
        ON DELETE CASCADE
);

-- =========================================================
-- FIN DEL SCRIPT DDL DE POSTGRESQL
-- =========================================================

COMMIT;

